logger = logging.getLogger(__name__)


def canonical_action_tokens(tokens: Iterable[str]) -> set[str]:
    """Normalize bounded action equivalents without adding factual aliases.

    Documents, destinations, channels, amounts and negations stay distinct.
    Handing in a document is deliberately not equated with uploading it.
    """
    equivalents = {
        'menyampaikan': 'menyerahkan', 'sampaikan': 'menyerahkan',
        'serahkan': 'menyerahkan',
        'mengecek': 'memeriksa', 'cek': 'memeriksa', 'periksa': 'memeriksa',
    }
    return {equivalents.get(token, token) for token in tokens}


def extract_requirement_statement(question: str, evidence: Any) -> str | None:
    """Quote an explicit, service-matched requirement statement; never infer a list.

    The normal grounding guard still validates the returned quote. This avoids
    asking a small local model to recreate requirements already stated verbatim.
    """
    query_tokens=set(re.findall(r'\w+', question.casefold()))
    for item in evidence or []:
        text=item.get('chunk','') if isinstance(item,dict) else getattr(item,'chunk','')
        title=item.get('title','') if isinstance(item,dict) else getattr(item,'title','')
        for line in str(text).splitlines():
            match=re.fullmatch(r'Persyaratan\s+([^:\n]{3,120}):\s*(\S.{0,1500})',line.strip(),re.IGNORECASE)
            if not match: continue
            scope=set(re.findall(r'\w+',match[1].casefold()))-{'untuk','layanan','dan'}
            if len(scope)<2 or not scope.issubset(query_tokens): continue
            # A citation is copied from source metadata, never generated by a model.
            return line.strip()+(f'\nSumber: {title}' if title else '')
    return None


def service_answer_facts(turn: dict, evidence: Any, previous: dict | None = None) -> dict | None:
    """Select one service and one aspect from current evidence, not model memory.

    Only explicitly labelled content is eligible. Never infer online availability
    or a duration from a service name, and never mix requirements across services.
    """
    if not turn.get('facet'): return None
    from .pdf_sop import table_facts
    selected_table = table_facts(turn, evidence)
    if selected_table is not None:
        return selected_table
    previous=previous or {}
    ignored={'permohonan','pengajuan','pelayanan','layanan','penerbitan','untuk','bagi','sop',
             'menurut','berdasarkan','sesuai','dalam','dokumen'}
    hint=set(re.findall(r'\w+',turn.get('topic_hint','').casefold()))-ignored
    candidates={}
    for item in evidence or []:
        get=lambda key,default='':item.get(key,default) if isinstance(item,dict) else getattr(item,key,default)
        source=str(get('source') or get('chunk'))
        match=re.search(r'^Persyaratan\s+([^:\n]+):\s*([^\n]+)',source,re.M|re.I)
        if not match:continue
        topic=match[1].strip();identifier=get('document_id')
        if not identifier:continue
        if turn.get('uses_context'):
            if identifier!=previous.get('document_id'):continue
        elif hint and not hint.issubset(set(re.findall(r'\w+', (topic+' '+str(get('title'))).casefold()))):continue
        candidates[identifier]={'topic':topic,'document_id':identifier,'title':get('title'),
                                'source':source,'score':get('score',0),'requirements':match.group(0)}
    if not candidates:return {'clarify':True,'missing':True} if turn.get('uses_context') else None
    if len(candidates)!=1:return {'clarify':True,'missing':False}
    selected=next(iter(candidates.values()));source=selected['source'];facet=turn['facet']
    rewrite_quote=''
    if facet=='requirements':
        quote=selected['requirements'];value=quote.split(':',1)[1].strip()
        fallback='Silakan siapkan '+value
    elif facet=='procedure':
        match=re.search(r'Prosedur:\s*(.+?\.)(?:\s|$)',source,re.S|re.I)
        quote=match[0] if match else ''
        value=match[1] if match else ''
        fallback='Alurnya sebagai berikut:\n'+'\n'.join('- '+x.strip() for x in value.split(';'))
        # A short process question needs its endpoints and main check, not every
        # internal disposition. These are copied clauses, never invented steps.
        if value and not turn.get('detailed'):
            steps=[x.strip().rstrip('.') for x in value.split(';') if x.strip()]
            check=next((x for x in steps[1:-1] if re.search(r'verifikasi\s+data|memeriksa\s+data|pemeriksaan\s+data',x,re.I)),None)
            selected_steps=[steps[0]]+([check] if check else [])+([steps[-1]] if len(steps)>1 else [])
            rewrite_quote='; '.join(selected_steps)+'.'
            fallback='Proses dimulai dengan '+steps[0]+'.'
            if check:
                noun=re.sub(r'^memverifikasi\b','verifikasi',check,flags=re.I)
                noun=re.sub(r'^memeriksa\b','pemeriksaan',noun,flags=re.I)
                fallback+=' Berikutnya ada '+noun+'.'
            if len(steps)>1:fallback+=' Di akhir alur, '+steps[-1]+'.'
    elif facet=='duration':
        quote=next((line.strip() for line in source.splitlines() if re.search(r'\b\d+\s+(?:hari|jam|menit)(?:\s+kerja)?\b',line,re.I)), '')
        duration=re.search(r'\b\d+\s+(?:hari|jam|menit)(?:\s+kerja)?\b',quote,re.I)
        fallback='Menurut SOP, waktunya '+duration[0].lower()+'.' if duration else ''
    else:
        quote=next((line.strip() for line in source.splitlines() if re.search(r'pengajuan|mengunggah|mengisi',line,re.I)
                    and re.search(r'online|daring|website|aplikasi|loket',line,re.I)), '')
        fallback=quote
    if not quote:
        subject={'procedure':'alur layanan','duration':'waktu penyelesaian','channel':'kanal '+turn.get('channel','layanan')}.get(facet,'persyaratan')
        fallback=f'Informasi {subject} belum tersedia dalam SOP ini.'
    return {**selected,'facet':facet,'quote':quote or source,'rewrite_quote':rewrite_quote or quote,'fallback':fallback,'unknown':not bool(quote),
            'proof':[{'title':selected['title'],'chunk':source,'score':selected['score']}]}


@dataclass
class GroundingResult:
    text: str
    grounded: bool
    reason: str
    unsupported_sentences: list[str]


class EvidenceGroundingGuard:
    """
    Validates whether an LLM response is sufficiently supported
    by retrieved knowledge evidence.

    Design principles:
    1. Generic topic overlap is NOT sufficient.
    2. Requirement questions require requirement evidence.
    3. Procedure questions require procedure evidence.
    4. Numeric claims require matching numeric evidence.
    5. Every substantive answer sentence must have evidence support.
    6. Empty evidence fails closed.
    7. Deterministic/local-rule responses can bypass this validator
       at the API routing layer.
    """

