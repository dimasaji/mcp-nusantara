    def __init__(
        self,
        min_sentence_overlap: float = 0.30,
        min_meaningful_tokens: int = 1,
    ) -> None:
        self.min_sentence_overlap = float(
            min_sentence_overlap
        )
        self.min_meaningful_tokens = int(
            min_meaningful_tokens
        )

    # ============================================================
    # PUBLIC API
    # ============================================================

    def validate(
        self,
        answer: Any,
        evidence: Any,
        intent_name: str | None = None,
    ) -> GroundingResult:
        """
        Validate an answer against retrieved evidence.

        intent_name is important for high-risk semantic categories:
        - ask_document_requirements
        - procedure/how-to questions
        - status questions
        - general information
        """

        text = self._normalize_text(answer)

        if not text:
            return GroundingResult(
                text="",
                grounded=False,
                reason="empty_answer",
                unsupported_sentences=[],
            )

        evidence_items = self._normalize_evidence(evidence)

        if not evidence_items:
            logger.warning(
                "Grounding rejected: no evidence."
            )
            return GroundingResult(
                text=text,
                grounded=False,
                reason="no_evidence",
                unsupported_sentences=[text],
            )

        evidence_texts = [
            item["text"]
            for item in evidence_items
            if item["text"]
        ]

        combined_evidence = " ".join(evidence_texts)

        question_type = self._normalize_intent(
            intent_name
        )

        sentences = self._split_sentences(text)
        # A source label must exactly match retrieved metadata. It is not a
        # requirement claim; fabricated labels and appended facts stay guarded.
        citation_labels = {f"sumber: {self._normalize_text(item['title'])}".casefold()
                           for item in evidence_items if item.get('title')}
        sentences = [sentence for sentence in sentences if sentence.casefold() not in citation_labels]
        if not sentences:
            return GroundingResult(text=text, grounded=False, reason='empty_answer',
                                   unsupported_sentences=[text])
        claim_text = ' '.join(sentences)

        # --------------------------------------------------------
        # VALID EVIDENCE-BASED ABSTENTION
        # --------------------------------------------------------
        # A pure abstention is allowed only when it does not contain
        # a requirement, procedure, or numeric claim. This prevents
        # the guard from treating a legitimate "information is not
        # available" response as hallucinated content while keeping
        # high-risk claims fail-closed.
        if (
            len(sentences) == 1
            and self._is_valid_abstention(sentences[0])
        ):
            return GroundingResult(
                text=text,
                grounded=True,
                reason="grounded_abstention",
                unsupported_sentences=[],
            )

        if not sentences:
            sentences = [text]

        unsupported: list[str] = []

        # --------------------------------------------------------
        # INTENT-SPECIFIC SAFETY
        # --------------------------------------------------------

        if question_type == "ask_document_requirements":
            # Topic overlap must never authorize inventing named documents.
            # Aliases share one identity (KK == Kartu Keluarga, KTP == KTP-el).
            document_terms = (r'\bktp(?:[- ]?el)?\b', r'\b(?:kk|kartu keluarga)\b',
                              r'\bakta kelahiran\b', r'\bsurat permohonan\b',
                              r'\bsurat pengantar\b', r'\bsurat pernyataan\b',
                              r'\bpaspor\b', r'\bnpwp\b')
            if any(re.search(term,claim_text,re.I) and not re.search(term,combined_evidence,re.I)
                   for term in document_terms):
                return GroundingResult(text=text,grounded=False,reason='required_document_not_supported',
                                       unsupported_sentences=sentences)
            if not self._evidence_contains_requirement_claim(
                combined_evidence
            ):
                logger.warning(
                    "Requirement validation failed: "
                    "evidence contains no explicit requirements."
                )
                return GroundingResult(
                    text=text,
                    grounded=False,
                    reason="requirement_evidence_missing",
                    unsupported_sentences=sentences,
                )

        # --------------------------------------------------------
        # SENTENCE VALIDATION
        # --------------------------------------------------------

        for sentence in sentences:
            sentence = sentence.strip()

            if not sentence:
                continue

            # Matching a number or most words cannot justify a new calendar,
            # unit, or service fact hidden in the rest of the same sentence.
            temporal_terms=r'\b(?:senin|selasa|rabu|kamis|jumat|sabtu|minggu|jam|menit|bulan|tahun)\b'
            claimed=set(re.findall(temporal_terms,sentence.casefold()))
            supported=set(re.findall(temporal_terms,combined_evidence.casefold()))
            if claimed-supported:
                unsupported.append(sentence)
                continue
            if question_type=='ask_document_requirements':
                # Requirements are a closed source list. Permit polite framing,
                # but not new actors, delivery steps, qualifications or facts.
                framing={'silakan','siapkan','menyiapkan','disiapkan','diperlukan',
                         'dibutuhkan','membutuhkan','memerlukan','harap','cukup',
                         'persyaratannya','syaratnya','berikut','menurut','sop',
                         'tercantum','berdasarkan','yaitu','terima','kasih','baik'}
                novel=(canonical_action_tokens(self._content_tokens(sentence))
                       - canonical_action_tokens(self._content_tokens(combined_evidence)) - framing)
                if novel:
                    unsupported.append(sentence)
                    continue

            if self._is_low_information_sentence(sentence):
                continue

            if self._contains_unsafe_claim(sentence):
                if not self._claim_supported(
                    sentence,
                    combined_evidence,
                    question_type,
                ):
                    unsupported.append(sentence)
                    continue

            if self._contains_numeric_claim(sentence):
                if not self._numbers_supported(
                    sentence,
                    combined_evidence,
                ):
                    unsupported.append(sentence)
                    continue

            if self._contains_requirement_claim(sentence):
                if not self._requirement_claim_supported(
                    sentence,
                    combined_evidence,
                ):
                    unsupported.append(sentence)
                    continue

            if self._contains_procedure_claim(sentence):
                if not self._procedure_claim_supported(
                    sentence,
                    combined_evidence,
                ):
                    unsupported.append(sentence)
                    continue

            if not self._general_sentence_supported(
                sentence,
                evidence_texts,
            ):
                unsupported.append(sentence)

        if unsupported:
            logger.warning(
                "Grounding rejected answer: "
                "reason=possible_unsupported_content "
                "unsupported=%d",
                len(unsupported),
            )

            return GroundingResult(
                text=text,
                grounded=False,
                reason="possible_unsupported_content",
                unsupported_sentences=unsupported,
            )

        return GroundingResult(
            text=text,
            grounded=True,
            reason="grounded",
            unsupported_sentences=[],
        )

    def validate_service_rewrite(self, answer: str, facts: dict) -> GroundingResult:
        """Validate the final phrasing, including service actions and certainty.

        Additional checks strengthen the ordinary guard; they do not accept a
        failed lexical/claim check or lower any retrieval/grounding threshold.
        """
        # Validated submission cells use the source label "Kelengkapan".
        # Their closed list and wording are checked below; prose requirements
        # still require the ordinary explicit-requirement markers.
        result=self.validate(answer,facts['proof'],
            'ask_document_requirements' if facts['facet']=='requirements' and not facts.get('table_derived') else '')
        if not result.grounded:return result
        if facts['unknown']:return result
        quote=facts['quote']
        if facts.get('table_derived'):
            from .sop_review import sop_wording_supported
            # A list's order is factual too. Token overlap cannot prove it;
            # table procedures must retain the complete ordered source quote.
            complete = (facts['facet'] != 'procedure' or
                        self._normalize_text(quote).casefold() == self._normalize_text(answer).casefold())
            if not complete or not sop_wording_supported(answer, quote):
                return GroundingResult(answer, False, 'table_wording_not_supported', [answer])
        concepts=(r'\b(?:datang|kunjungi|mendatangi)\b',r'\b(?:unggah|mengunggah|upload)\b',
                  r'\b(?:bayar|membayar|gratis|biaya)\b',r'\b(?:online|daring|website|aplikasi)\b',
                  r'\b(?:ktp(?:-el)?|ktpel)\b',r'\b(?:kk|kartu keluarga)\b',r'\bformulir\b',
                  r'\bsurat pengantar\b',r'\b(?:pasti|dijamin|selalu|maksimal|minimal)\b',
                  r'\b(?:tidak|tanpa|bukan)\b')
        invalid=any(re.search(pattern,answer,re.I) and not re.search(pattern,quote,re.I) for pattern in concepts)
        # A source quote cannot establish an individual transaction or make
        # the assistant speak as the office. Citations are rendered from metadata.
        invalid=invalid or bool(re.search(r'\b(?:sumber|evidence|fakta)\s*:',answer,re.I))
        for pattern in (r'\b(?:sudah|telah|berhasil)\b',r'\b(?:kami|pelanggan)\b'):
            invalid=invalid or bool(re.search(pattern,answer,re.I) and not re.search(pattern,quote,re.I))
        if re.search(r'\b(?:anda|pemohon)\s+(?:harus\s+)?(?:memverifikasi|mendisposisi|menstempel|mengarsipkan)\b',answer,re.I):
            invalid=True
        if facts['facet']=='requirements':
            value=quote.split(':',1)[-1]
            # A fluent sentence that omits the requested documents is not an answer.
            invalid=invalid or not canonical_action_tokens(self._meaningful_tokens(value)).issubset(
                canonical_action_tokens(self._content_tokens(answer)))
        if facts['facet']=='duration':
            expected=re.search(r'\b\d+\s+(?:hari|jam|menit)(?:\s+kerja)?\b',quote,re.I)
            invalid=invalid or expected is None or expected[0].casefold() not in answer.casefold()
            invalid=invalid or not bool(re.search(r'\bsop\b|tercantum|menurut|sumber',answer,re.I))
        if invalid:
            return GroundingResult(text=answer,grounded=False,reason='possible_unsupported_content',unsupported_sentences=[answer])
        return result

    def build_grounded_context(
        self,
        evidence: Any,
    ) -> str:
        evidence_items = self._normalize_evidence(
            evidence
        )

        if not evidence_items:
            return (
                "Tidak ada evidence knowledge base "
                "yang tersedia."
            )

        parts: list[str] = []

        for index, item in enumerate(
            evidence_items,
            start=1,
        ):
            title = item.get(
                "title",
                "Knowledge Base",
            )
            content = item.get("text", "")

            parts.append(
                f"[EVIDENCE {index}] "
                f"{title}\n"
                f"{content}"
            )

        return "\n\n".join(parts)

    def build_system_instruction(self) -> str:
        return (
            "Jawab hanya berdasarkan EVIDENCE yang diberikan. "
            "Jangan membuat persyaratan, prosedur, angka, "
            "durasi, biaya, alamat, atau langkah layanan "
            "yang tidak terdapat secara eksplisit dalam "
            "EVIDENCE. Jika informasi tidak tersedia, "
            "katakan bahwa informasi tersebut belum tersedia "
            "dalam knowledge base."
        )

    # ============================================================
    # EVIDENCE NORMALIZATION
    # ============================================================

    def _normalize_evidence(
        self,
        evidence: Any,
    ) -> list[dict[str, str]]:
        if evidence is None:
            return []

        if isinstance(evidence, str):
            text = evidence.strip()
            return (
                [{"title": "Evidence", "text": text}]
                if text
                else []
            )

        if isinstance(evidence, dict):
            return self._normalize_evidence_item(
                evidence
            )

        if isinstance(evidence, Iterable):
            result: list[dict[str, str]] = []

            for item in evidence:
                normalized = (
                    self._normalize_evidence_item(item)
                )

                result.extend(normalized)

            return result

        normalized = self._normalize_evidence_item(
            evidence
        )

        return normalized

    def _normalize_evidence_item(
        self,
        item: Any,
    ) -> list[dict[str, str]]:
        if item is None:
            return []

        if isinstance(item, str):
            text = item.strip()

            return (
                [{"title": "Evidence", "text": text}]
                if text
                else []
            )

        if isinstance(item, dict):
            title = str(
                item.get(
                    "title",
                    item.get(
                        "document_id",
                        "Evidence",
                    ),
                )
                or "Evidence"
            )

            text = (
                item.get("chunk")
                or item.get("source")
                or item.get("text")
                or item.get("content")
                or ""
            )

            text = self._normalize_text(text)

            if not text:
                return []

            return [
                {
                    "title": title,
                    "text": text,
                }
            ]

        title = str(
            getattr(
                item,
                "title",
                getattr(
                    item,
                    "document_id",
                    "Evidence",
                ),
            )
            or "Evidence"
        )

        text = (
            getattr(item, "chunk", None)
            or getattr(item, "source", None)
            or getattr(item, "text", None)
            or getattr(item, "content", None)
            or ""
        )

        text = self._normalize_text(text)

        if not text:
            return []

        return [
            {
                "title": title,
                "text": text,
            }
        ]

    # ============================================================
    # TEXT PROCESSING
    # ============================================================

    def _normalize_text(
        self,
        value: Any,
    ) -> str:
        if value is None:
            return ""

        return re.sub(
            r"\s+",
            " ",
            str(value),
        ).strip()

    def _split_sentences(
        self,
        text: str,
    ) -> list[str]:
        parts = self.SENTENCE_PATTERN.split(
            text.strip()
        )

        return [
            part.strip()
            for part in parts
            if part.strip()
        ]

    def _content_tokens(
        self,
        text: str,
    ) -> set[str]:
        tokens = re.findall(
            r"\b\w+\b",
            text.lower(),
            flags=re.UNICODE,
        )

        return {
            token
            for token in tokens
            if len(token) > 1
            and token not in self.STOPWORDS
        }

    def _meaningful_tokens(
        self,
        text: str,
    ) -> set[str]:
        return (
            self._content_tokens(text)
            - self.GENERIC_DOMAIN_TERMS
        )

    # ============================================================
    # INTENT
    # ============================================================

    def _normalize_intent(
        self,
        intent_name: str | None,
    ) -> str:
        if not intent_name:
            return ""

        return str(intent_name).strip().lower()

    # ============================================================
    # ABSTENTION VALIDATION
    # ============================================================

    def _is_valid_abstention(
        self,
        sentence: str,
    ) -> bool:
        """
        Accept a pure evidence-based abstention without requiring
        lexical overlap with the evidence.

        This is intentionally narrow:
        - accepts statements that explicitly say information is
          unavailable / not present in evidence
        - rejects abstentions that themselves contain requirement,
          procedure, or numeric claims

        Example accepted:
            "Informasi tersebut belum tersedia dalam EVIDENCE."

        Example rejected:
            "Syarat membuat KTP-el adalah ..."
        """
        lower = self._normalize_text(sentence).lower()

        if not lower:
            return False

        abstention_markers = (
            "belum tercantum",
            "tidak tercantum",
            "belum disebutkan",
            "tidak disebutkan",
            "tidak tersedia",
            "belum tersedia",
            "tidak ada informasi",
            "belum ada informasi",
            "tidak ditemukan informasi",
            "belum ditemukan informasi",
            "informasi tidak tersedia",
            "informasi tersebut tidak tersedia",
            "informasi tersebut belum tersedia",
            "evidence tidak memenuhi",
            "evidence tidak memiliki",
            "tidak terdapat informasi",
            "tidak terdapat data",
            "belum terdapat informasi",
        )

        # Contact absence need not be prefixed with "informasi". Limit the
        # subject and the entire sentence so other factual clauses cannot pass.
        missing_statement = bool(re.fullmatch(
            r"(?:informasi\s+)?(?:nomor\s+|alamat\s+)?"
            r"(?:whatsapp|telepon|email|e-mail|kontak)(?:\s+petugas)?"
            r"\s+(?:belum|tidak)\s+ditemukan"
            r"(?:\s+(?:dalam|di|pada)\s+(?:sop|dokumen|evidence)"
            r"(?:\s+(?:ini|tersebut))?)?[.!]?",
            lower,
        ))

        from .sop_review import contact_absence_statement
        if not (missing_statement or contact_absence_statement(sentence)) and not any(
            marker in lower
            for marker in abstention_markers
        ):
            return False

        # A refusal containing a concrete high-risk claim is NOT
        # a pure abstention and must still be grounded normally.
        if self._contains_requirement_claim(sentence):
            return False

        if self._contains_procedure_claim(sentence):
            return False

        if self._contains_numeric_claim(sentence):
            return False

        return True

    # ============================================================
    # REQUIREMENT VALIDATION
    # ============================================================

    def _contains_requirement_claim(
        self,
        sentence: str,
    ) -> bool:
        lower = sentence.lower()

        return any(
            marker in lower
            for marker in self.REQUIREMENT_MARKERS
        )

    def _evidence_contains_requirement_claim(
        self,
        evidence: str,
    ) -> bool:
        lower = evidence.lower()

        return any(
            marker in lower
            for marker in self.REQUIREMENT_MARKERS
        )

    def _requirement_claim_supported(
        self,
        sentence: str,
        evidence: str,
    ) -> bool:
        """
        Requirement claims require explicit requirement
        language in the evidence.

        Generic words such as KTP, dokumen, administrasi,
        status, diterbitkan, or ketentuan are insufficient.
        """

        if not self._contains_requirement_claim(
            sentence
        ):
            return True

        if not self._evidence_contains_requirement_claim(
            evidence
        ):
            return False

        sentence_tokens = (
            self._meaningful_tokens(sentence)
        )

        evidence_tokens = (
            self._meaningful_tokens(evidence)
        )

        overlap = (
            sentence_tokens
            & evidence_tokens
        )

        return len(overlap) >= 1

    # ============================================================
    # PROCEDURE VALIDATION
    # ============================================================

    def _contains_procedure_claim(
        self,
        sentence: str,
    ) -> bool:
        """
        Detect procedural/action claims.

        A sentence is procedural when it contains explicit
        action/instruction language OR an obligation combined
        with an action.
        """

        lower = self._normalize_text(sentence).lower()

        # Explicit procedural markers.
        explicit_markers = (
            "langkah",
            "cara",
            "prosedur",
            "tahapan",
            "ikuti",
            "lakukan",
            "melakukan",
            "klik",
            "buka",
            "pilih",
            "masukkan",
            "isi",
            "unggah",
            "upload",
            "ajukan",
            "mengajukan",
            "datang",
            "bawa",
            "periksa",
            "cek",
            "mengecek",
        )

        # Obligation + action is definitely procedural.
        obligation_markers = (
            "harus",
            "wajib",
            "perlu",
            "diharuskan",
        )

        has_explicit = any(
            marker in lower
            for marker in explicit_markers
        )

        has_obligation = any(
            marker in lower
            for marker in obligation_markers
        )

        # Critical rule:
        # "harus melakukan ...", "wajib mengajukan ...",
        # etc. are procedural claims.
        if has_obligation and has_explicit:
            return True

        return has_explicit

    def _evidence_contains_procedure_claim(
        self,
        evidence: str,
    ) -> bool:
        """
        Detect EXPLICIT procedural instructions in evidence.

        Capability/status statements such as:
            "status dapat diperiksa melalui layanan"

        are NOT considered procedural evidence.

        Procedural evidence requires explicit action/instruction
        language such as:
            langkah, cara, lakukan, klik, buka, pilih, masukkan,
            unggah, isi, ajukan, datang, bawa, ikuti, tahapan,
            prosedur.
        """

        lower = self._normalize_text(evidence).lower()

        explicit_procedure_markers = (
            "langkah",
            "cara",
            "prosedur",
            "tahapan",
            "ikuti",
            "lakukan",
            "melakukan langkah",
            "klik",
            "buka",
            "pilih",
            "masukkan",
            "isi",
            "unggah",
            "upload",
            "ajukan",
            "mengajukan",
            "datang",
            "bawa",
        )

        return any(
            marker in lower
            for marker in explicit_procedure_markers
        )

    def _procedure_claim_supported(
        self,
        sentence: str,
        evidence: str,
    ) -> bool:
        """
        Procedure claims require explicit procedural evidence.

        Lexical overlap of one token is NOT sufficient.
        Evidence must contain procedural language and provide
        meaningful lexical support for the claimed action.
        """

        if not self._contains_procedure_claim(sentence):
            return True

        # Evidence must explicitly describe a procedure/action.
        if not self._evidence_contains_procedure_claim(evidence):
            return False

        sentence_tokens = canonical_action_tokens(self._meaningful_tokens(sentence))
        evidence_tokens = canonical_action_tokens(self._meaningful_tokens(evidence))

        if not sentence_tokens or not evidence_tokens:
            return False

        overlap = sentence_tokens & evidence_tokens

        # One shared token is too weak for a procedural claim.
        # Require at least 2 meaningful overlapping tokens.
        if len(overlap) < 2:
            return False

        # Require meaningful lexical coverage of the claim.
        coverage = len(overlap) / max(len(sentence_tokens), 1)

        # Procedure claims need stronger evidence than ordinary
        # informational statements.
        return coverage >= 0.30


    # ============================================================
    # NUMERIC VALIDATION
    # ============================================================

    def _contains_numeric_claim(
        self,
        sentence: str,
    ) -> bool:
        return bool(
            self.NUMBER_PATTERN.search(sentence)
        )

    def _numbers_supported(
        self,
        sentence: str,
        evidence: str,
    ) -> bool:
        answer_numbers = set(
            self.NUMBER_PATTERN.findall(
                sentence
            )
        )

        if not answer_numbers:
            return True

        evidence_numbers = set(
            self.NUMBER_PATTERN.findall(
                evidence
            )
        )

        return answer_numbers.issubset(
            evidence_numbers
        )

    # ============================================================
    # GENERAL VALIDATION
    # ============================================================

    def _general_sentence_supported(
        self,
        sentence: str,
        evidence_texts: list[str],
    ) -> bool:
        sentence_tokens = (
            self._content_tokens(sentence)
        )

        if not sentence_tokens:
            return True

        best_overlap = 0.0

        for evidence in evidence_texts:
            evidence_tokens = (
                self._content_tokens(evidence)
            )

            if not evidence_tokens:
                continue

            overlap = (
                sentence_tokens
                & evidence_tokens
            )

            score = (
                len(overlap)
                / max(
                    len(sentence_tokens),
                    1,
                )
            )

            best_overlap = max(
                best_overlap,
                score,
            )

        return (
            best_overlap
            >= self.min_sentence_overlap
        )

    def _claim_supported(
        self,
        sentence: str,
        evidence: str,
        intent_name: str,
    ) -> bool:
        if self._contains_requirement_claim(
            sentence
        ):
            return self._requirement_claim_supported(
                sentence,
                evidence,
            )

        if self._contains_procedure_claim(
            sentence
        ):
            return self._procedure_claim_supported(
                sentence,
                evidence,
            )

        if self._contains_numeric_claim(
            sentence
        ):
            return self._numbers_supported(
                sentence,
                evidence,
            )

        return self._general_sentence_supported(
            sentence,
            [evidence],
        )

    # ============================================================
    # SAFETY
    # ============================================================

    def _contains_unsafe_claim(
        self,
        sentence: str,
    ) -> bool:
        lower = sentence.lower()

        markers = (
            self.REQUIREMENT_MARKERS
            + self.PROCEDURE_MARKERS
            + (
                "biaya",
                "rp",
                "rupiah",
                "hari kerja",
                "jam",
                "menit",
                "usia",
                "berlaku",
                "masa berlaku",
            )
        )

        return any(
            marker in lower
            for marker in markers
        )

    def _is_low_information_sentence(
        self,
        sentence: str,
    ) -> bool:
        tokens = self._content_tokens(
            sentence
        )

        return len(tokens) < 2


