"""Opt-in, bounded session history over the existing LongTermMemory store.

Session identifiers are bearer capabilities generated by new_session(). No global
or 'web' history, automatic capture, vector store or second memory engine.
"""
from __future__ import annotations

import hashlib
import re
import secrets
import threading
import time
from pathlib import Path

from app.memory.memory import LongTermMemory
from app.observability.logging import redact


class SessionMemory:
    def __init__(self, root: Path, *, retention_s: int = 86400, max_turns: int = 6,
                 max_chars: int = 8000, clock=time.time):
        if retention_s < 1 or max_turns < 1 or max_chars < 100:
            raise ValueError("invalid memory limits")
        self.store = LongTermMemory(root)
        self.retention_s, self.max_turns, self.max_chars = retention_s, max_turns, max_chars
        self.clock = clock
        self.lock = threading.RLock()
        self.purge_expired()

    @staticmethod
    def _key(session_id: str) -> str:
        if not re.fullmatch(r"mem-[a-f0-9]{64}", session_id):
            raise ValueError("use a session returned by /v2/memory/sessions")
        return "chat-" + hashlib.sha256(session_id.encode()).hexdigest()

    def new_session(self) -> str:
        session = "mem-" + secrets.token_hex(32)
        with self.lock:
            self.purge_expired()
            if len(self.store.list_keys("chat-")) >= 1000:
                raise ValueError("memory session capacity reached")
            self.store.save(self._key(session), {"expires_at": self.clock() + self.retention_s, "turns": []},
                            metadata={"purpose": "explicit session continuity", "retention_s": self.retention_s})
        return session

    def purge_expired(self) -> int:
        removed = 0
        with self.lock:
            for key in self.store.list_keys("chat-"):
                item = self.store.get(key)
                if not isinstance(item, dict) or item.get("expires_at", 0) <= self.clock():
                    removed += self.store.delete(key)
        return removed

    def _load(self, session_id: str) -> dict:
        key = self._key(session_id)
        item = self.store.get(key)
        if not isinstance(item, dict) or item.get("expires_at", 0) <= self.clock():
            self.store.delete(key)
            raise ValueError("memory session unavailable or expired")
        return item

    def read(self, session_id: str) -> str:
        with self.lock:
            item = self._load(session_id)
            return "\n".join(f"User: {t['query']}\nAssistant: {t['answer']}" for t in item["turns"])

    def write(self, session_id: str, query: str, answer: str) -> None:
        with self.lock:
            item = self._load(session_id)
            turns = item["turns"] + [{"query": redact(query)[:1000], "answer": redact(answer)[:2000]}]
            turns = turns[-self.max_turns:]
            while sum(len(t["query"]) + len(t["answer"]) + 20 for t in turns) > self.max_chars:
                turns.pop(0)
            item["turns"] = turns
            self.store.save(self._key(session_id), item, metadata={
                "purpose": "explicit session continuity", "retention_s": self.retention_s})

    def delete(self, session_id: str) -> bool:
        with self.lock:
            return self.store.delete(self._key(session_id))
