import {test,expect} from '@playwright/test';
import {mkdirSync,writeFileSync} from 'node:fs';

test.use({channel:'chromium',headless:true,viewport:{width:1360,height:1000},trace:'off',video:'off'});
test('existing file is reused and duplicate process history is summarized on live UI',async({page,request})=>{
  test.skip(process.env.NUSANTARA_DOCLING_LIVE!=='1','Explicit live run only');
  test.setTimeout(180000);
  const origin='http://127.0.0.1:5180',token=process.env.NUSANTARA_ADMIN_TOKEN!;
  const headers={'X-Admin-Token':token};
  const before=await(await request.get(origin+'/v1/knowledge/pipeline/status',{headers})).json();
  const duplicate=before.runs.find((r:{status:string;filename:string})=>r.status==='DUPLICATE'&&r.filename==='SOP Permohonan Data Pribadi (PIAK-03).txt');
  expect(duplicate).toBeTruthy();
  const source=await request.get(`${origin}/v1/knowledge/pipeline/reviews/${duplicate.document_id}/source`,{headers});
  expect(source.ok()).toBeTruthy();
  const raw=await source.body();let uploads=0;
  page.on('request',r=>{if(r.method()==='POST'&&r.url()===origin+'/v1/knowledge/pipeline/documents')uploads++;});
  await page.goto(origin+'/knowledge');
  await page.getByLabel('Token operator',{exact:true}).fill(token);
  await page.getByRole('button',{name:'Verifikasi akses',exact:true}).click();
  await expect(page.getByText('Akses operator terverifikasi. Anda dapat mengunggah file.')).toBeVisible();
  await page.getByText('Riwayat proses sebelumnya',{exact:true}).click();
  const history=page.getByRole('region',{name:'History knowledge'});
  const identical=before.runs.filter((r:typeof duplicate)=>r.status==='DUPLICATE'&&r.source_sha256===duplicate.source_sha256&&r.document_id===duplicate.document_id&&r.filename===duplicate.filename&&r.reason===duplicate.reason);
  const grouped=history.getByRole('row').filter({hasText:duplicate.filename}).filter({hasText:'DUPLICATE'});
  await expect(grouped).toHaveCount(1);
  await expect(grouped).toContainText(`${identical.length} percobaan identik`);
  await history.getByRole('button',{name:`Tampilkan semua catatan (${before.runs.length})`,exact:true}).click();
  await expect(grouped).toHaveCount(identical.length);
  await history.getByRole('button',{name:'Ringkas pengulangan',exact:true}).click();
  await page.getByText('Tambahkan dokumen baru',{exact:true}).click();
  await page.getByLabel('Pilih dokumen').setInputFiles({name:'salinan-dengan-nama-baru.txt',mimeType:'text/plain',buffer:raw});
  await page.getByRole('button',{name:'Proses dan validasi',exact:true}).click();
  await expect(page.getByText('File identik sudah tersedia. Gunakan dokumen tersimpan; tidak perlu unggah ulang.')).toBeVisible();
  await expect(page.getByRole('link',{name:'Tanyakan dokumen tersimpan',exact:true})).toBeVisible();
  expect(uploads).toBe(0);
  const after=await(await request.get(origin+'/v1/knowledge/pipeline/status',{headers})).json();
  expect(after.runs.map((r:{run_id:string})=>r.run_id)).toEqual(before.runs.map((r:{run_id:string})=>r.run_id));
  expect(after.documents_indexed).toBe(before.documents_indexed);
  mkdirSync('../artifacts/knowledge-duplicate',{recursive:true});
  writeFileSync('../artifacts/knowledge-duplicate/result.json',JSON.stringify({status:'PASS',grouped_duplicates:identical.length,uploads,runs_before:before.runs.length,runs_after:after.runs.length,documents:after.documents_indexed},null,2));
  await history.getByRole('heading',{name:'History proses',exact:true}).scrollIntoViewIfNeeded();
  await page.screenshot({path:`../artifacts/knowledge-duplicate/history-${Date.now()}.png`});
});
